/// A lifting stage (15.4.4.1): type 1–4, shift `s`, offset `d` and taps.
pub(crate) struct Stage {
    pub kind: u8,
    pub s: u32,
    pub d: i64,
    pub taps: &'static [i64],
}

/// A wavelet filter (Tables 15.1–15.6): its synthesis stages and the bit shift after synthesis.
pub(crate) struct Filter {
    pub stages: &'static [Stage],
    pub shift: u32,
}

const fn st(kind: u8, s: u32, d: i64, taps: &'static [i64]) -> Stage {
    Stage { kind, s, d, taps }
}

