/// A base video format (Table B.1): frame size, colour difference format, source sampling, top
/// field first, frame rate preset, pixel aspect ratio preset, clean area, signal range preset and
/// colour spec preset.
pub(crate) struct BaseFormat {
    pub w: u32,
    pub h: u32,
    pub cdf: u8,
    pub interlaced: bool,
    pub tff: bool,
    pub rate: u8,
    pub par: u8,
    pub clean: [u32; 4],
    pub range: u8,
    pub spec: u8,
}

const fn bf(w: u32, h: u32, cdf: u8, interlaced: bool, tff: bool, rate: u8, par: u8, clean: [u32; 4], range: u8, spec: u8) -> BaseFormat {
    BaseFormat { w, h, cdf, interlaced, tff, rate, par, clean, range, spec }
}

