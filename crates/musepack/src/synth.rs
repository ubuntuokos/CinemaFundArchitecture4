/// `mpc_synthese_filter_float_internal`: 36 × 32 output samples of one channel from its 36
/// subband vectors `y`, written to `out[0..1152]`; `v` is the channel's V buffer.
pub(crate) fn synthesize(win: &[[f32; 16]; 32], v: &mut [f32], y: &[[f32; 32]; 36], out: &mut [f32]) {
    if v.len() < V_LEN || out.len() < 36 * 32 {
        return;
    }
    v.copy_within(0..960, V_MEM);
    const TAPS: [usize; 16] = [0, 96, 128, 224, 256, 352, 384, 480, 512, 608, 640, 736, 768, 864, 896, 992];
    for (n, (yn, o)) in y.iter().zip(out.chunks_exact_mut(32)).enumerate() {
        let base = V_MEM - 64 * (n + 1);
        compute_new_v(yn, &mut v[base..base + 64]);
        for (k, (d, s)) in win.iter().zip(o.iter_mut()).enumerate() {
            let p = base + k;
            let mut acc = v[p + TAPS[0]] * d[0];
            for (t, &tap) in TAPS.iter().enumerate().skip(1) {
                acc += v[p + tap] * d[t];
            }
            *s = acc;
        }
    }
}
