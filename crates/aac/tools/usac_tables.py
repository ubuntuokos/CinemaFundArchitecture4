#!/usr/bin/env python3
"""Generate the USAC (xHE-AAC) decoder tables from a libxaac checkout.

Usage: python3 -I usac_tables.py /path/to/libxaac > ../src/usac/<name>_tables.rs

libxaac (https://android.googlesource.com/platform/external/libxaac, Apache-2.0,
Copyright (C) 2018 The Android Open Source Project, originally developed by Ittiam Systems)
holds the tables of ISO/IEC 23003-3 / 23003-4 in C arrays; this script copies the values verbatim.
"""

import re
import sys

HEADER = """// Generated by crates/aac/tools/usac_tables.py from libxaac ({src}).
// libxaac: Copyright (C) 2018 The Android Open Source Project, Apache License 2.0
// (originally developed by Ittiam Systems Pvt. Ltd, Bangalore). Do not edit by hand.
"""


def extract(path, name):
    """Return the flat list of values of C array `name` in file `path`."""
    src = open(path).read()
    m = re.search(r"\b" + re.escape(name) + r"\s*(\[[^=;]*\])\s*=\s*\{", src)
    if not m:
        raise SystemExit("missing " + name + " in " + path)
    i = m.end()
    depth = 1
    j = i
    while depth:
        c = src[j]
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
        j += 1
    body = src[i : j - 1]
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    body = re.sub(r"//[^\n]*", "", body)
    body = re.sub(r"\(\s*(?:UWORD|WORD|FLOAT)\d*\s*\)", "", body)
    body = re.sub(r"\(\s*(?:unsigned|signed)?\s*(?:short|int|char|long)\s*\)", "", body)
    out = []
    for part in re.split(r"[{},]", body):
        p = part.strip()
        if not p:
            continue
        # float suffix (`1.5f`), but not the hex digit F (`0x1F`)
        p = re.sub(r"(?<![0-9a-fA-FxX])(\d+(?:\.\d*)?(?:[eE][-+]?\d+)?)[fF]\b", r"\1", p)
        p = re.sub(r"(0x[0-9a-fA-F]+|\d+)[uUlL]+\b", r"\1", p)
        out.append(eval(p, {"__builtins__": {}}))
    return out


def emit(rust_name, ty, vals, per_line=12, dims=None):
    n = len(vals)
    if dims:
        rows = dims[0]
        cols = n // rows
        lines = [f"pub const {rust_name}: [[{ty}; {cols}]; {rows}] = ["]
        for r in range(rows):
            row = vals[r * cols : (r + 1) * cols]
            lines.append("    [" + ", ".join(str(v) for v in row) + "],")
        lines.append("];")
        return "\n".join(lines)
    lines = [f"pub const {rust_name}: [{ty}; {n}] = ["]
    for k in range(0, n, per_line):
        lines.append("    " + ", ".join(str(v) for v in vals[k : k + per_line]) + ",")
    lines.append("];")
    return "\n".join(lines)


SETS = {
    "arith": (
        "decoder/ixheaacd_arith_dec.c",
        [
            ("ixheaacd_ari_cf_r", "ARI_CF_R", "u16", [3]),
            ("ixheaacd_ari_lookup_m", "ARI_LOOKUP_M", "u8", None),
            ("ixheaacd_ari_hash_m", "ARI_HASH_M", "u32", None),
            ("ixheaacd_ari_hash_m_1", "ARI_HASH_M_PKI", "u8", None),
            ("ixheaacd_ari_cf_m", "ARI_CF_M", "u16", [64]),
        ],
    ),
}


def main():
    root = sys.argv[1]
    which = sys.argv[2] if len(sys.argv) > 2 else "arith"
    src, tables = SETS[which]
    print(HEADER.format(src=src))
    for cname, rname, ty, dims in tables:
        vals = extract(root + "/" + src, cname)
        print(emit(rname, ty, vals, dims=dims))
        print()


if __name__ == "__main__":
    main()
