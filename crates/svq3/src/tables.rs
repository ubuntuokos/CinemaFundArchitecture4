/// `ff_h264_chroma_qp[0][qp]` (8-bit) for `qp` in 0..52.
pub fn chroma_qp(qp: usize) -> i32 {
    const TAIL: [u8; 22] = [29, 30, 31, 32, 32, 33, 34, 34, 35, 35, 36, 36, 37, 37, 37, 38, 38, 38, 39, 39, 39, 39];
    if qp < 30 { qp as i32 } else { i32::from(TAIL[(qp - 30).min(21)]) }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn scan_tables_are_permutations() {
        for s in [&SVQ3_SCAN[..], &ZIGZAG_SCAN[..]] {
            let mut v = s.to_vec();
            v.sort_unstable();
            assert_eq!(v, (0..16).collect::<Vec<u8>>());
        }
        assert_eq!(SCAN8[0], 12);
        assert_eq!(chroma_qp(29), 29);
        assert_eq!(chroma_qp(43), 37);
    }
}
