#[test]
fn ciede2000_sharma_table() {
    for (i, r) in SHARMA.iter().enumerate() {
        let (x, y) = (Lab::new(r[0], r[1], r[2]), Lab::new(r[3], r[4], r[5]));
        let (d, back) = (ciede2000(&x, &y), ciede2000(&y, &x));
        assert!((d - r[6]).abs() < 5e-5, "pair {}: {d} vs {}", i + 1, r[6]);
        assert!((d - back).abs() < 1e-12, "pair {} not symmetric", i + 1);
    }
}

struct Lcg(u64);
impl Lcg {
    fn next(&mut self) -> i64 {
        self.0 = (self.0 * 1_103_515_245 + 12_345) & 0x7fff_ffff;
        (self.0 >> 16) as i64
    }
}

/// Reference and distorted planes as in the oracle script: a ramp plus noise, and that plus
/// clamped noise of ±`amp`.
fn planes(w: usize, h: usize, seed: u64, maxv: i64, amp: i64) -> (Vec<i64>, Vec<i64>) {
    let mut r = Lcg(seed);
    let (mut a, mut b) = (Vec::new(), Vec::new());
    for y in 0..h as i64 {
        for x in 0..w as i64 {
            let v = (x * 4 + y * 2 + r.next() % 64) % (maxv + 1);
            a.push(v);
            b.push((v + r.next() % (2 * amp + 1) - amp).clamp(0, maxv));
        }
    }
    (a, b)
}

#[test]
fn ssim_matches_scikit_image() {
    let (a, b) = planes(64, 48, 12345, 255, 15);
    let (a8, b8): (Vec<u8>, Vec<u8>) = (a.iter().map(|&v| v as u8).collect(), b.iter().map(|&v| v as u8).collect());
    let s = ssim_u8(&a8, &b8, 64, 48).unwrap();
    assert!((s - 0.938_811_250_196_598_7).abs() < 1e-12, "{s}");
    let (af, bf): (Vec<f32>, Vec<f32>) = (a.iter().map(|&v| v as f32).collect(), b.iter().map(|&v| v as f32).collect());
    assert!((ssim(&af, &bf, 64, 48, 255.0).unwrap() - s).abs() < 1e-12);

    let (a, b) = planes(40, 33, 777, 1023, 60);
    let (a16, b16): (Vec<u16>, Vec<u16>) = (a.iter().map(|&v| v as u16).collect(), b.iter().map(|&v| v as u16).collect());
    let s = ssim_u16(&a16, &b16, 40, 33, 10).unwrap();
    assert!((s - 0.601_866_345_565_703_5).abs() < 1e-12, "{s}");
}

#[test]
fn srgb_to_lab_matches_scikit_image() {
    let cases: [([u8; 3], [f64; 3]); 5] = [
        ([255, 0, 0], [53.240_587_943_744_9, 80.092_308_225_692_2, 67.202_751_044_428_7]),
        ([0, 255, 0], [87.735_099_488_318_95, -86.183_029_744_395_01, 83.179_703_175_384_52]),
        ([0, 0, 255], [32.295_672_565_013_51, 79.185_590_911_765_56, -107.857_300_206_694_89]),
        ([128, 64, 200], [41.884_782_338_092_87, 53.521_301_725_253_88, -60.355_009_622_317_86]),
        ([10, 200, 30], [70.500_131_994_611_7, -70.513_831_073_335_48, 64.940_839_962_619_55]),
    ];
    // scikit-image uses the rounded sRGB matrix of IEC 61966-2-1; ours is derived from the BT.709
    // chromaticities, so they agree to a few thousandths of a unit.
    for (rgb, want) in cases {
        let got = srgb8_to_lab(rgb[0], rgb[1], rgb[2]);
        for (g, w) in [got.l, got.a, got.b].iter().zip(want) {
            assert!((g - w).abs() < 0.01, "{rgb:?}: {got:?} vs {want:?}");
        }
    }
}

#[test]
fn image_delta_e_matches_scikit_image() {
    let (w, h) = (16, 8);
    let mut r = Lcg(99);
    let a: Vec<u8> = (0..w * h * 3).map(|_| (r.next() % 256) as u8).collect();
    let b: Vec<u8> = a.iter().map(|&v| (i64::from(v) + r.next() % 21 - 10).clamp(0, 255) as u8).collect();
    let s = delta_e_srgb8(&a, &b, w, h, 3).unwrap();
    assert!((s.mean - 2.430_050_991_652_506_4).abs() < 1e-3, "{s:?}");
    assert!((s.max - 12.140_908_456_604_473).abs() < 1e-2, "{s:?}");
    assert!((s.above_jnd - 0.890_625).abs() < 1e-12, "{s:?}");

    // RGBA: alpha is ignored.
    let rgba = |v: &[u8]| v.chunks_exact(3).flat_map(|p| [p[0], p[1], p[2], 7]).collect::<Vec<u8>>();
    assert_eq!(delta_e_srgb8(&rgba(&a), &rgba(&b), w, h, 4).unwrap(), s);
    assert_eq!(delta_e_srgb8(&a, &a, w, h, 3).unwrap(), DeltaEStats::default());
    assert_eq!(delta_e_srgb8(&a, &b, w, h, 2), Err(MetricError::Channels(2)));
    assert!(matches!(delta_e_srgb8(&a, &b, w, h + 1, 3), Err(MetricError::BadLength { .. })));
}
