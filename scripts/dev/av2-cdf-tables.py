#!/usr/bin/env python3
"""Generate crates/av2/src/cdf_default.rs from the AV2 spec package attachments.

Usage: av2-cdf-tables.py <av2-spec>/v1.0.0/attachments [--check]

Reads every default_*_cdf.h (the Default_*_Cdf arrays of spec §9.3), derives each table's
shape from its brace nesting, and writes one flat u16 static per table plus an index.
The attachments are not committed; see crates/av2/README.md for the provenance.
"""
import re
import sys
from pathlib import Path

TESTS = r'''#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_cdf_is_well_formed() {
        assert_eq!(ALL.len(), 180);
        for t in ALL {
            let n1 = *t.dims.last().expect("dims");
            assert!(n1 >= 3, "{}", t.name);
            assert_eq!(t.data.len(), t.dims.iter().product::<usize>(), "{}", t.name);
            for cdf in t.data.chunks(n1) {
                let n = n1 - 1;
                // Values are non-decreasing and at most 1 << 15; the rate index is in range;
                // the counter starts at zero.
                assert!(cdf[..n - 1].windows(2).all(|w| w[0] <= w[1]), "{}", t.name);
                assert!(cdf[..n - 1].iter().all(|&v| v <= 1 << 15), "{}", t.name);
                assert!(cdf[n - 1] < 125, "{} rate", t.name);
                assert_eq!(cdf[n], 0, "{} counter", t.name);
            }
        }
    }

    #[test]
    fn known_shapes() {
        assert_eq!(DEFAULT_SKIP_CDF.dims, &[6, 3]);
        assert_eq!(DEFAULT_SKIP_CDF.data[..3], [25865, 25, 0]);
        assert_eq!(DEFAULT_COEFF_BASE_CDF.data[..5], [12360, 26392, 29943, 26, 0]);
    }
}'''

OUT = Path(__file__).resolve().parents[2] / "crates/av2/src/cdf_default.rs"


def parse(text):
    m = re.match(r"\s*(Default_\w+_Cdf)\s*(?:\[[^\]]*\]\s*)+=\s*", text)
    if not m:
        raise SystemExit("unrecognised table header")
    name, body = m.group(1), text[m.end():]
    shape, flat, stack, counts = None, [], [], []
    num = ""
    depth = 0
    shapes = {}  # depth -> set of child counts
    for ch in body + " ":
        if ch.isdigit():
            num += ch
            continue
        if num:
            flat.append(int(num))
            counts[-1] += 1
            num = ""
        if ch == "{":
            counts.append(0)
        elif ch == "}":
            n = counts.pop()
            shapes.setdefault(len(counts), set()).add(n)
            if counts:
                counts[-1] += 1 if True else 0
                # a closed group counts as one child of its parent, but numbers add too
        # other characters ignored
    dims = []
    for d in sorted(shapes):
        s = shapes[d]
        if len(s) != 1:
            raise SystemExit(f"{name}: ragged at depth {d}: {s}")
        dims.append(next(iter(s)))
    return name, dims, flat


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    if len(args) != 1:
        raise SystemExit(__doc__)
    src = Path(args[0])
    tables = []
    for p in sorted(src.glob("default_*_cdf.h")):
        name, dims, flat = parse(p.read_text())
        total = 1
        for d in dims:
            total *= d
        if total != len(flat):
            raise SystemExit(f"{p.name}: shape {dims} has {total} cells but {len(flat)} numbers")
        if max(flat) > 32768:
            raise SystemExit(f"{p.name}: value out of range")
        tables.append((name, dims, flat))
    out = [
        "//! Default CDF tables (spec §9.3, `Default_*_Cdf`), generated by",
        "//! `scripts/dev/av2-cdf-tables.py` from the `default_*_cdf.h` attachments of the AV2",
        "//! specification v1.0.0. Do not edit by hand.",
        "//!",
        "//! Each table is a flat row-major `u16` array; `dims` gives the nesting, the last dimension",
        "//! being one CDF (`N + 1` entries: values, adaptation rate index, counter).",
        "",
        "/// One default CDF table.",
        "pub struct CdfTable {",
        "    pub name: &'static str,",
        "    pub dims: &'static [usize],",
        "    pub data: &'static [u16],",
        "}",
        "",
    ]
    for name, dims, flat in tables:
        const = name.upper()
        out.append(f"pub static {const}: CdfTable = CdfTable {{")
        out.append(f'    name: "{name}",')
        out.append(f"    dims: &{dims},")
        out.append("    data: &[")
        for i in range(0, len(flat), 16):
            out.append("        " + ", ".join(map(str, flat[i:i + 16])) + ",")
        out.append("    ],")
        out.append("};")
        out.append("")
    out.append("/// Every default CDF table, in file-name order.")
    out.append("pub static ALL: &[&CdfTable] = &[")
    for name, _, _ in tables:
        out.append(f"    &{name.upper()},")
    out.append("];")
    out.append("")
    out.append(TESTS)
    text = "\n".join(out)
    if "--check" in sys.argv:
        if OUT.read_text() != text:
            raise SystemExit("cdf_default.rs is out of date")
        print("ok", len(tables), "tables")
    else:
        OUT.write_text(text)
        print("wrote", OUT, len(tables), "tables,", sum(len(f) for _, _, f in tables), "values")


main()
