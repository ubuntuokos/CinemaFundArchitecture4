#!/usr/bin/env python3
"""Generate crates/av2/src/block_tables.rs from the AV2 spec package attachments and spec text.

Usage: av2-block-tables.py <av2-spec>/v1.0.0/attachments <spec-text> [--check]

<spec-text> is a plain-text rendering of the spec PDF; only the inline Subsampled_Size table
(§ 5.20.7.26) is read from it.

Block-size enumerations and lookup tables (Partition_Subsize, H_Partition_Midsize,
Num_4x4_Blocks_*, Mi_*_Log2). Block names map to the numbering of spec Table 6.22.
"""
import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[2] / "crates/av2/src/block_tables.rs"
BLOCKS = ("4X4 4X8 8X4 8X8 8X16 16X8 16X16 16X32 32X16 32X32 32X64 64X32 64X64 64X128 128X64 "
          "128X128 128X256 256X128 256X256 4X16 16X4 8X32 32X8 16X64 64X16 4X32 32X4 8X64 64X8").split()
BLOCK_INVALID = 255


def body(path):
    text = path.read_text()
    return text[text.index("=") + 1:]


def ints(path):
    return [int(x) for x in re.findall(r"-?\d+", re.sub(r"//[^\n]*", "", body(path)))]


def blocks(path):
    out = []
    for tok in re.findall(r"BLOCK_[0-9A-Z]+", re.sub(r"//[^\n]*", "", body(path))):
        name = tok[6:]
        out.append(BLOCK_INVALID if name == "INVALID" else BLOCKS.index(name))
    return out


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    if len(args) != 2:
        raise SystemExit(__doc__)
    a = Path(args[0])
    spec = Path(args[1]).read_text()
    marker = "Subsampled_Size[ BLOCK_SIZES ][ 2 ][ 2 ] = {"
    start = spec.index(marker) + len(marker)
    end = spec.index("5.20.7.27. Coefficients syntax", start)
    ss = []
    for tok in re.findall(r"BLOCK_[0-9A-Z]+", spec[start:end]):
        name = tok[6:]
        ss.append(BLOCK_INVALID if name == "INVALID" else BLOCKS.index(name))
    assert len(ss) == 29 * 4, len(ss)
    sub = blocks(a / "partition_subsize.h")
    assert len(sub) == 10 * 29, len(sub)
    mid = blocks(a / "h_partition_midsize.h")
    assert len(mid) == 29
    tables = {
        "NUM_4X4_WIDE": ints(a / "num_4x4_blocks_wide.h"),
        "NUM_4X4_HIGH": ints(a / "num_4x4_blocks_high.h"),
        "MI_WIDTH_LOG2": ints(a / "mi_width_log2.h"),
        "MI_HEIGHT_LOG2": ints(a / "mi_height_log2.h"),
    }
    for k, v in tables.items():
        assert len(v) == 29, (k, len(v))
    out = [
        "//! Block-size lookup tables (spec Table 6.22 numbering), generated by",
        "//! `scripts/dev/av2-block-tables.py` from the AV2 specification v1.0.0 attachments.",
        "//! Do not edit by hand.",
        "",
        "/// Number of block sizes.",
        "pub const BLOCK_SIZES: usize = 29;",
        "/// Marker for an invalid block size in the lookup tables.",
        "pub const BLOCK_INVALID: u8 = 255;",
        "",
    ]
    for i, n in enumerate(BLOCKS):
        out.append(f"pub const BLOCK_{n}: u8 = {i};")
    out.append("")
    for k, v in tables.items():
        out.append(f"pub const {k}: [u8; 29] = {v};")
    out.append("")
    out.append("pub const H_PARTITION_MIDSIZE: [u8; 29] = " + str(mid).replace("255", "BLOCK_INVALID") + ";")
    out.append("")
    out.append("/// `Subsampled_Size[ bSize ][ subx ][ suby ]`, flattened as `bSize * 4 + subx * 2 + suby`.")
    out.append("pub const SUBSAMPLED_SIZE: [u8; 116] = " + str(ss).replace("255", "BLOCK_INVALID") + ";")
    out.append("")
    out.append("/// `Partition_Subsize[ partition ][ bSize ]`.")
    out.append("pub const PARTITION_SUBSIZE: [[u8; 29]; 10] = [")
    for p in range(10):
        row = sub[p * 29:(p + 1) * 29]
        out.append("    " + str(row).replace("255", "BLOCK_INVALID") + ",")
    out.append("];")
    out.append("")
    text = "\n".join(out)
    if "--check" in sys.argv:
        if OUT.read_text() != text:
            raise SystemExit("block_tables.rs is out of date")
        print("ok")
    else:
        OUT.write_text(text)
        print("wrote", OUT)


main()
